//! Singleton resources. These are the state that lives across systems
//! but only once per app.
//!
//! For per-run state (current seed, biome, score, time remaining) see
//! `RunState` — it gets reset at the start of every run.

use bevy::prelude::*;

/// Global Cascade Mode state. One per app.
///
/// Phase 1 prototype: every `cascade_interval_s` (default 75s) a
/// 30s window opens where every `CascadeAffected` entity (enemies
/// today, enemy projectiles + particles later) runs at
/// `cascade_scale` × normal speed. The player and player
/// projectiles are not `CascadeAffected` and run at full speed.
///
/// Two timers: `interval_timer` counts down to the next window
/// opening (used while `active` is false), `duration_timer` counts
/// down the current window (used while `active` is true).
/// `cascade_state_system` flips between them and resets the
/// appropriate one. The cycle is deterministic and asymmetric
/// (long quiet, short loud) by design — see PLAN.md §2.
///
/// Phase 2+ will also drive: 4× XP / 4× loot rarity on kills
/// during Cascade, +5s window extension on Beacon kills, and a
/// damage-taken multiplier. The `kills_during` and `chain_extends`
/// fields are in place now so we can land those without another
/// resource migration.
#[derive(Resource)]
pub struct CascadeState {
    pub active: bool,
    pub time_remaining: f32,
    pub kills_during: u32,
    pub chain_extends: u32,
    pub interval_timer: Timer,
    pub duration_timer: Timer,
}

impl Default for CascadeState {
    fn default() -> Self {
        Self {
            active: false,
            time_remaining: 0.0,
            kills_during: 0,
            chain_extends: 0,
            // Start with a 30s "warmup" so the first cascade doesn't
            // hit the player the moment they spawn. The interval
            // re-arms to its full length after each cascade ends,
            // so subsequent cascades are spaced by the full default.
            interval_timer: Timer::from_seconds(30.0, TimerMode::Once),
            duration_timer: Timer::from_seconds(0.0, TimerMode::Once),
        }
    }
}

/// Phase 2 P6 (Crab Champions run): tracks the current floor's
/// room layout, the player's current room, and the floor
/// number for difficulty scaling. `rooms` is mutated as new
/// rooms are generated when the player takes a teleport pad.
///
/// `floor_number` starts at 0 and advances on boss kills.
/// Used by `generate_room` to pick the wave composition and
/// by the difficulty scaler to ramp enemy HP/damage.
///
/// `Default` gives an empty `rooms` vec and `current_room = 0`,
/// which is the placeholder state before the first room is
/// generated by `setup_rooms_system` (OnEnter InRun).
#[derive(Resource)]
pub struct FloorState {
    pub rooms: Vec<crate::components::Room>,
    pub current_room: crate::components::RoomId,
    pub floor_number: u32,
}

impl Default for FloorState {
    fn default() -> Self {
        Self {
            rooms: Vec::new(),
            current_room: crate::components::RoomId(0),
            floor_number: 0,
        }
    }
}

/// Phase 2.3: per-run seeded RNG. The single source of
/// randomness for the whole run — every `random_spawn_position`,
/// `boss_spawn_angle`, etc. reads from this resource. The seed
/// is set in `enter_in_run_system` from `RunState.seed` (which
/// itself is set from system time at run start).
///
/// `state` is a 64-bit xorshift register. `next_unit()` returns
/// a uniform f32 in [0, 1). The state is `Cell`-free because
/// `ResMut<RunRng>` gives unique access per-system.
///
/// Why a Resource, not `rand::random()`? `rand::random()`
/// uses a thread-local generator seeded from the OS — runs
/// aren't reproducible, the sequence is global, and the
/// phase-2 multiplayer prototype (Phase 5) needs every
/// client's RNG to advance identically. A `ResMut<RunRng>` is
/// the lightest-weight determinism we can get without a full
/// lockstep layer.
#[derive(Resource)]
pub struct RunRng {
    pub state: u64,
}

impl RunRng {
    /// Construct a new `RunRng` from a 64-bit seed. The seed
    /// 0 is rejected because xorshift's all-zero state is a
    /// fixed point (every `next_unit()` returns 0). The
    /// fallback `0xCAFEBABE` is arbitrary — any non-zero
    /// constant works.
    pub fn new(seed: u64) -> Self {
        let state = if seed == 0 { 0xCAFEBABE } else { seed };
        Self { state }
    }

    /// Advance the xorshift register by one step and return
    /// a uniform f32 in [0, 1). Same algorithm as the Phase 1
    /// ad-hoc helper in `random_spawn_position` and
    /// `boss_spawn_system` — the constants (13, 7, 17) are
    /// the standard "best" xorshift64 magic numbers (per
    /// Vigna, "An experimental exploration of Marsaglia's
    /// xorshift generators, scrambled", 2014).
    pub fn next_unit(&mut self) -> f32 {
        let mut x = self.state;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.state = x;
        ((x >> 40) as f32) / ((1u32 << 24) as f32)
    }
}

impl Default for RunRng {
    fn default() -> Self {
        // Seed 0 is rejected inside `new`. A real run picks
        // its seed in `enter_in_run_system` (from
        // system time). The default is just a placeholder so
        // the Resource initializer doesn't panic.
        Self::new(0xDEADBEEF_CAFEBABE)
    }
}

/// Per-run state. Reset on `InRun` state entry.
#[derive(Resource)]
pub struct RunState {
    pub seed: u64,
    pub biome_index: u32,
    pub time_elapsed: f32,
    pub time_cap: f32, // 300s for a 5-minute run
    /// Phase 2 P5: XP counter, bumped on every kill. Acts as
    /// the run's "score" for the player — the HUD shows the
    /// number directly. During Cascade, each kill gives
    /// `xp_per_kill * cascade_xp_multiplier` so the same
    /// combat generates 4× XP, matching the design-doc
    /// promise of "kills during Cascade: 4× XP".
    pub xp: u32,
    pub enemies_killed: u32,
    /// Phase 2 P5 (Cascade beacon): flipped to `true` by the
    /// cascade-start handler the frame it spawns a beacon,
    /// flipped to `false` when the beacon dies. Defensive
    /// guard against double-spawn if `CascadeStartEvent`
    /// ever fires twice in the same window.
    ///
    /// Replaces the Phase 1 "boss-death → cascade hook"
    /// comment: the boss's death no longer gates the
    /// cascade (cascade is a tempo event on its own
    /// interval, per `phase_2_3_2_design_shift.md` §2.1).
    pub cascade_beacon_alive: bool,
    // Phase 1 mini-boss: set to `true` the frame the boss
    // spawns (via `boss_spawn_system` in player.rs). Used as
    // a one-shot gate so the boss spawns exactly once per run;
    // `enter_in_run_system` resets it back to `false` on each
    // new run (death → restart, or MainMenu → start).
    pub boss_spawned: bool,
    // Phase 1 (Vampire Survivors fusion) pickup stacks. Each
    // DamageUp / FireRateUp / SpeedUp pickup adds 1 to the
    // corresponding stack (capped at 8 per kind to prevent
    // runaway scaling). Regen is special: it stacks flat
    // HP/sec on top of a base of 0, no cap. All effects are
    // permanent for the run; `restart_system` resets them.
    pub damage_stacks: u32,
    pub fire_rate_stacks: u32,
    pub speed_stacks: u32,
    pub regen_per_sec: f32,
}

impl Default for RunState {
    fn default() -> Self {
        Self {
            seed: 0,
            biome_index: 0,
            time_elapsed: 0.0,
            time_cap: 300.0,
            xp: 0,
            enemies_killed: 0,
            cascade_beacon_alive: false,
            boss_spawned: false,
            damage_stacks: 0,
            fire_rate_stacks: 0,
            speed_stacks: 0,
            regen_per_sec: 0.0,
        }
    }
}

/// Brief global freeze when an enemy dies. Inserted by the
/// projectile-damage system on a killing blow; ticks down each frame;
/// any gameplay system (movement, AI, fire, contact) early-returns
/// while the resource is present, so the hitstop is felt uniformly.
/// The resource is removed when the timer elapses.
#[derive(Resource)]
pub struct Hitstop {
    pub timer: Timer,
}

/// Global screen-shake state. Set to a non-zero intensity by the
/// contact-damage system when the player takes a hit; the camera
/// follow system reads the current value, adds a decaying random
/// offset, and decays the remaining time each frame.
#[derive(Resource, Default)]
pub struct ScreenShake {
    pub intensity: f32,
    pub duration: f32,
    pub remaining: f32,
}

