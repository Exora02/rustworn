use crate::components::GameOverReason;
use crate::components::PlayerClass;
use bevy::prelude::*;

/// Phase 2 P6 (Crab Champions run): tracks the current floor's
/// room layout, the player's current room, and the floor
/// number for difficulty scaling. `rooms` is mutated as new
/// rooms are generated when the player takes a teleport pad.
///
/// `floor_number` starts at 0 and advances on boss kills.
/// Used by `generate_room` to pick the wave composition and
/// by the difficulty scaler to ramp enemy HP/damage.
///
/// `Default` gives an empty `rooms` vec and `current_room = 0`,
/// which is the placeholder state before the first room is
/// generated by `setup_rooms_system` (OnEnter InRun).
#[derive(Resource)]
pub struct FloorState {
    pub rooms: Vec<crate::components::Room>,
    pub current_room: crate::components::RoomId,
    pub floor_number: u32,
}

impl Default for FloorState {
    fn default() -> Self {
        Self {
            rooms: Vec::new(),
            current_room: crate::components::RoomId(0),
            floor_number: 0,
        }
    }
}

/// Per-run state. Reset on `InRun` state entry.
#[derive(Resource)]
pub struct RunState {
    pub seed: u64,
    pub biome_index: u32,
    pub time_elapsed: f32,
    pub time_cap: f32, // 300s for a 5-minute run
    /// Phase 2 P5: XP counter, bumped on every kill. Acts as
    /// the run's "score" for the player — the HUD shows the
    /// number directly. During Cascade, each kill gives
    /// `xp_per_kill * cascade_xp_multiplier` so the same
    /// combat generates 4× XP, matching the design-doc
    /// promise of "kills during Cascade: 4× XP".
    pub xp: u32,
    pub enemies_killed: u32,
    /// Phase 2 P5 (Cascade beacon): flipped to `true` by the
    /// cascade-start handler the frame it spawns a beacon,
    /// flipped to `false` when the beacon dies. Defensive
    /// guard against double-spawn if `CascadeStartEvent`
    /// ever fires twice in the same window.
    ///
    /// Replaces the Phase 1 "boss-death → cascade hook"
    /// comment: the boss's death no longer gates the
    /// cascade (cascade is a tempo event on its own
    /// interval, per `phase_2_3_2_design_shift.md` §2.1).
    pub cascade_beacon_alive: bool,
    // Phase 1 mini-boss: set to `true` the frame the boss
    // spawns (via `boss_spawn_system` in player.rs). Used as
    // a one-shot gate so the boss spawns exactly once per run;
    // `enter_in_run_system` resets it back to `false` on each
    // new run (death → restart, or MainMenu → start).
    pub boss_spawned: bool,
    // Phase 1 (Vampire Survivors fusion) pickup stacks. Each
    // DamageUp / FireRateUp / SpeedUp pickup adds 1 to the
    // corresponding stack (capped at 8 per kind to prevent
    // runaway scaling). Regen is special: it stacks flat
    // HP/sec on top of a base of 0, no cap. All effects are
    // permanent for the run; `restart_system` resets them.
    pub damage_stacks: u32,
    pub fire_rate_stacks: u32,
    pub speed_stacks: u32,
    pub regen_per_sec: f32,
    /// Brotato-style curse: increases spawn rate and loot quality
    /// in exchange for harder rooms. Set by curse shrine rewards.
    /// Each point is ~10% more spawn rate + scaling loot bonus.
    pub curse: u32,
    /// Phase 3c (Crab Champions shop): gold currency. Earned by
    /// killing enemies and breaking breakables; spent in shop
    /// rooms between combat rooms. Persists across rooms, resets
    /// on death/restart.
    pub gold: u32,
    /// Phase 3d armor: flat damage reduction applied before each
    /// hit. Each ArmorUp pickup adds 0.5; player takes
    /// max(0, raw_damage - armor) per hit. Caps at 4.0 so the
    /// player can never become fully immune.
    pub armor: f32,
    /// Why the current run ended (or will end). Updated by the
    /// extraction / death systems; read by the HUD overlay to
    /// show "GAME OVER" vs "EXTRACTED!" and by (future) meta-
    /// progression systems.
    pub game_over_reason: GameOverReason,
    /// Character class selected on the main menu. Applied on run start.
    pub selected_class: PlayerClass,
    /// Marauder ability cooldown timer for the grenade throw (3s).
    /// A finished timer = ready to fire; ticking = ability on cooldown.
    pub marauder_ability_cooldown: Timer,
    /// Engineer ability: cooldown timer for turret deploy/recall.
    pub engineer_turret_cooldown: Timer,
    /// Engineer ability: whether a turret is currently deployed.
    pub engineer_turret_deployed: bool,
    /// Spectre teleport cooldown timer. Starts finished (ready to use).
    /// Reset to 1.5s on teleport, ticked each frame.
    pub spectre_teleport_cooldown: Timer,
    /// Unlockable: Crown of Greed — multiplies all gold income.
    pub gold_mult: f32,
    /// Unlockable: Vampire — heal HP on every enemy kill.
    pub vampire_heal: f32,
    /// Unlockable: Thorns — reflect damage back to attackers.
    pub thorns_damage: f32,
}

impl Default for RunState {
    fn default() -> Self {
        Self {
            seed: 0,
            biome_index: 0,
            time_elapsed: 0.0,
            time_cap: 300.0,
            xp: 0,
            enemies_killed: 0,
            cascade_beacon_alive: false,
            boss_spawned: false,
            damage_stacks: 0,
            fire_rate_stacks: 0,
            speed_stacks: 0,
            regen_per_sec: 0.0,
            curse: 0,
            gold: 0,
            armor: 0.0,
            game_over_reason: GameOverReason::Died,
            selected_class: PlayerClass::Marauder,
            // Starts finished (0s), so the first grenade is available immediately.
            marauder_ability_cooldown: Timer::from_seconds(0.0, TimerMode::Once),
            // Starts finished (0s), so the first turret deploy is available immediately.
            engineer_turret_cooldown: Timer::from_seconds(0.0, TimerMode::Once),
            engineer_turret_deployed: false,
            // Starts finished (0s), so the first teleport is available immediately.
            spectre_teleport_cooldown: Timer::from_seconds(0.0, TimerMode::Once),
            gold_mult: 1.0,
            vampire_heal: 0.0,
            thorns_damage: 0.0,
        }
    }
}

/// Set when the run ends (death or extraction). Consumed by the
/// HUD overlay and (future) meta-progression systems.
#[derive(Resource, Default)]
pub struct RunSummary {
    pub extracted: bool,
    pub floor_reached: u32,
    pub gold_earned: u32,
    pub xp_earned: u32,
    pub enemies_killed: u32,
    pub time_elapsed: f32,
}